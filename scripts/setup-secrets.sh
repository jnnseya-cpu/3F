#!/usr/bin/env bash
# =============================================================================
# setup-secrets.sh — provision all runtime secrets for Le Congo D'Abord
# into Firebase App Hosting (Cloud Secret Manager = the "admin account").
#
# WHAT IT DOES
#   1. Generates the 6 "self-made" secrets (random strings, no provider needed).
#   2. Writes them to frontend/.env.local for local dev (gitignored).
#   3. Sets ALL secrets in Firebase App Hosting Secret Manager IF you pass
#      --apply and have the Firebase CLI authenticated + a backend id.
#   4. For PROVIDER keys (Firebase/AI/payments/email), it prints exactly what to
#      obtain and the command to set each — only you can create those.
#
# USAGE
#   Local dev only (writes .env.local, prints provider steps):
#     bash scripts/setup-secrets.sh
#   Provision to production (requires: npm i -g firebase-tools && firebase login):
#     BACKEND=<your-apphosting-backend-id> bash scripts/setup-secrets.sh --apply
#
# NOTE: this script never commits secrets. .env.local and *.generated are gitignored.
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."            # repo/frontend if run from scripts/, adjust below
ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
FRONTEND="$ROOT/frontend"
ENVFILE="$FRONTEND/.env.local"
APPLY="${1:-}"

gen() { openssl rand -base64 48 | tr -d '\n'; }

# --- 1. self-made secrets (regenerated fresh each run) ---
declare -A SELF=(
  [MEMBER_TOKEN_SECRET]="$(gen)"
  [HUMAN_GATE_SECRET]="$(gen)"
  [SENTINEL_ADMIN_KEY]="$(gen)"
  [CRON_SECRET]="$(gen)"
  [JWT_SECRET]="$(gen)"
  [NEWSLETTER_SECRET]="$(gen)"
)

# --- 2. write local .env.local (for `npm run dev`) ---
echo "# Generated by setup-secrets.sh on $(date -u) — DO NOT COMMIT" > "$ENVFILE"
for k in "${!SELF[@]}"; do echo "$k=${SELF[$k]}" >> "$ENVFILE"; done
cat >> "$ENVFILE" <<'LOCAL'
# --- fill these from your provider accounts (see ADMIN_SETUP.md) ---
NEXT_PUBLIC_SITE_URL=https://congodabord.cd
FIREBASE_PROJECT_ID=
FIREBASE_API_KEY=
FIREBASE_CLIENT_EMAIL=
FIREBASE_PRIVATE_KEY=
ANTHROPIC_API_KEY=
OPENAI_API_KEY=
GEMINI_API_KEY=
BITRIPAY_API_KEY=
BITRIPAY_API_URL=
BITRIPAY_WEBHOOK_SECRET=
RESEND_API_KEY=
NEWSLETTER_FROM="Le Congo D'Abord <news@congodabord.cd>"
NEXT_PUBLIC_META_PIXEL_ID=
NEXT_PUBLIC_GA_ID=
LOCAL
chmod 600 "$ENVFILE"
echo "✓ wrote self-made secrets + placeholders to $ENVFILE (gitignored)"

# --- 3. production: set in Secret Manager ---
if [ "$APPLY" = "--apply" ]; then
  : "${BACKEND:?Set BACKEND=<apphosting-backend-id> to apply}"
  command -v firebase >/dev/null || { echo "firebase CLI missing: npm i -g firebase-tools && firebase login"; exit 1; }
  for k in "${!SELF[@]}"; do
    printf '%s' "${SELF[$k]}" | firebase apphosting:secrets:set "$k" --data-file - --force
    firebase apphosting:secrets:grantaccess "$k" --backend "$BACKEND" || true
    echo "✓ set + granted $k"
  done
  echo
  echo "Self-made secrets provisioned. Now set the PROVIDER secrets below the same way:"
else
  echo "(dev mode — re-run with --apply and BACKEND=<id> to push to Secret Manager)"
fi

cat <<'PROVIDER'

────────────────────────────────────────────────────────────────────────────
PROVIDER-SUPPLIED secrets — only you can obtain these. For each:
  firebase apphosting:secrets:set <NAME>        # paste the value when prompted
  firebase apphosting:secrets:grantaccess <NAME> --backend <BACKEND>
then UNCOMMENT its line in frontend/apphosting.yaml and `git push` to roll out.

  FIREBASE_PROJECT_ID / FIREBASE_API_KEY / FIREBASE_CLIENT_EMAIL / FIREBASE_PRIVATE_KEY
      → Firebase console → Project settings → Service accounts → Generate key
  ANTHROPIC_API_KEY / OPENAI_API_KEY / GEMINI_API_KEY
      → each AI provider console (at least one; fallback order Claude→OpenAI→Gemini)
  BITRIPAY_API_KEY / BITRIPAY_API_URL / BITRIPAY_WEBHOOK_SECRET
      → your mobile-money gateway merchant dashboard
  RESEND_API_KEY  (+ NEWSLETTER_FROM as plain value)
      → resend.com, after verifying your sending domain

PUBLIC (not secret — set as plain `value:` in apphosting.yaml, safe in the bundle):
  NEXT_PUBLIC_SITE_URL, NEXT_PUBLIC_META_PIXEL_ID, NEXT_PUBLIC_GA_ID
────────────────────────────────────────────────────────────────────────────
PROVIDER
